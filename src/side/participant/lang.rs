//! Language and texts of the public registration page.

use chrono::NaiveDateTime;

use crate::time::to_local;

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Lang {
    #[default]
    De,
    En,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::De, Lang::En];

    pub fn label(self) -> &'static str {
        match self {
            Lang::De => "DE",
            Lang::En => "EN",
        }
    }

    pub fn index(self) -> usize {
        Self::ALL.iter().position(|lang| *lang == self).unwrap_or(0)
    }

    pub fn txt(self) -> &'static Txt {
        match self {
            Lang::De => &DE,
            Lang::En => &EN,
        }
    }

    /// Deadline in the visitor's local time (storage timestamps are UTC).
    /// The language of the address editor (the guest's pages show it in the visitor's language).
    pub(crate) fn address(self) -> crate::side::details::address::AddressLang {
        match self {
            Lang::De => crate::side::details::address::AddressLang::De,
            Lang::En => crate::side::details::address::AddressLang::En,
        }
    }

    pub fn format_deadline(self, utc: NaiveDateTime) -> String {
        let local = to_local(utc);
        match self {
            Lang::De => local.format("%d.%m.%Y, %H:%M Uhr").to_string(),
            Lang::En => local.format("%d.%m.%Y, %H:%M").to_string(),
        }
    }
}

/// Puts a number of days into a text with the placeholder `{days}`.
pub fn with_days(text: &str, days: u32) -> String {
    text.replace("{days}", &days.to_string())
}

